func (m Model) helpView() string {
	page := helpPages[m.helpPage]
	return m.decoratedPanel(fmt.Sprintf("学习手册 %d/%d · %s", m.helpPage+1, len(helpPages), page.title), page.lines,
		keyHints("1–5 / ←→", "章节", "↑↓/jk", "滚动", "Esc", "返回"))
}
